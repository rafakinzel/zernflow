-- Leads from the link-in-bio quiz at thiagoborrelli.com/links-bio/.
--
-- That page is a separate, static site: it is not part of BorrelliChat and
-- nothing in this app reads or writes this table. It lives in this project
-- only so the link in bio no longer needs a Supabase project of its own. The
-- columns, types and order are copied from the table it used before
-- (leads_quiz in the "Link na bio [TB]" project), so the page keeps sending
-- the same 22 fields and the rows copied across keep their ids and dates.
--
-- Who can do what:
--   - A visitor (anon) can add a lead and nothing else: no reading, no
--     changing, no deleting, and only the 22 fields the form sends. id and
--     created_at are set by the database, so a visitor cannot pick an id or
--     backdate a lead.
--   - A signed-in BorrelliChat user (authenticated) gets nothing. Being able
--     to log in to the bot is not a reason to see these people's answers.
--   - The service role keeps the project default, which is how the rows are
--     copied in and how they are read from the dashboard.
--
-- New tables in `public` are granted everything for anon and authenticated by
-- the project's default privileges, so those grants are taken back explicitly
-- below rather than trusted to RLS alone. RLS is still on, as the second lock.
--
-- New ids start at 1,000,000. Leads keep arriving at the old project while
-- browsers still hold the old page (it is cached for up to 62 days), and they
-- are copied across later with their own small ids. Starting high means a lead
-- written here can never take an id an old one still needs.
create table public.link_bio_leads (
  id                    bigint generated by default as identity (start with 1000000) primary key,
  created_at            timestamptz default now(),
  nome                  text,
  email                 text,
  whatsapp              text,
  p1                    text,
  p2                    text,
  p3                    text,
  p4                    text,
  p5                    text,
  servico_recomendado   text,
  servicos_alternativos jsonb,
  scores                jsonb,
  user_agent            text,
  aceita_contato        boolean,
  consentimento_em      timestamptz,
  consentimento_texto   text,
  utm_source            text,
  utm_medium            text,
  utm_campaign          text,
  utm_content           text,
  utm_term              text,
  referrer              text,
  landing_url           text
);

comment on table public.link_bio_leads is
  'Leads from the link-in-bio quiz (thiagoborrelli.com/links-bio/). Not used by BorrelliChat. Visitors may insert only; read with the service role.';

alter table public.link_bio_leads enable row level security;

-- Take back what the default privileges handed out.
revoke all on table public.link_bio_leads from public, anon, authenticated;
revoke all on sequence public.link_bio_leads_id_seq from public, anon, authenticated;

-- The only thing a visitor may do: insert these 22 columns. An identity
-- column needs no grant on its sequence for the default to fire.
grant insert (
  nome, email, whatsapp,
  p1, p2, p3, p4, p5,
  servico_recomendado, servicos_alternativos, scores, user_agent,
  aceita_contato, consentimento_em, consentimento_texto,
  utm_source, utm_medium, utm_campaign, utm_content, utm_term,
  referrer, landing_url
) on table public.link_bio_leads to anon;

drop policy if exists "Link bio visitors can submit a lead" on public.link_bio_leads;
create policy "Link bio visitors can submit a lead"
  on public.link_bio_leads for insert
  to anon
  with check (true);
